import express from "express";
import cors from "cors";
import QuizModel from "./model/quiz.js";
import QuizRouter from "./routes/quizRoutes.js";
import optionQuizRouter from "./routes/OptionQuizRoutes.js";
import OptionQuizModel from "./model/option-quiz.js";
import ArticleRoute from "./routes/articleRoutes.js";
import ArticleModel from "./model/article.js";
import SpesiesRoute from "./routes/spesiesRoute.js";
import SpesiesModel from "./model/spesies.js";
import PendidikanRoute from "./routes/pendidikanRoutes.js";
import PendidikanModel from "./model/pendidikan.js";
import PerawatanModel from "./model/perawatan.js";
import PerawatanRoute from "./routes/perawatanRoutes.js";
import HabitatModel from "./model/habitat.js";
import HabitatRoute from "./routes/habitatRoutes.js";
const app = express();
const port = 3000;
app.use(express.json());
app.use(cors());
app.use("/uploads", express.static("uploads"));
app.use(QuizRouter);
app.use(optionQuizRouter);
app.use(ArticleRoute);
app.use(SpesiesRoute);
app.use(PendidikanRoute);
app.use(PerawatanRoute);
app.use(HabitatRoute);
app.get("/", (req, res) => {
  res.send("Welcome to my Api");
});
app.listen(port, async () => {
  console.log("server berhasil dijalankan");
  await QuizModel.sync();
  console.log("berhasil membuat database quiz");
  await OptionQuizModel.sync();
  console.log("berhasil membuat database option quiz");
  await ArticleModel.sync();
  console.log("berhasil membuat database Artikel");
  await SpesiesModel.sync();
  console.log("berhasil membuat database Spesies");
  await PendidikanModel.sync();
  console.log("berhasil membuat database pendidikan");
  await PerawatanModel.sync();
  console.log("berhasil membuat database perawatan");
  await HabitatModel.sync();
  console.log("berhasil membuat database habitat");
});
